"""Generate src/tmem_ops.cuh: one device function per tcgen05.ld / tcgen05.st
shape and repeat count (the PTX takes a fixed-length register vector, so each
form needs its own asm statement)."""
import os

SHAPES = {  # shape -> (regs per repeat, repeats)
    "32x32b": (1, [1, 2, 4, 8, 16, 32, 64, 128]),
    "16x64b": (1, [1, 2, 4, 8, 16, 32, 64, 128]),
    "16x128b": (2, [1, 2, 4, 8, 16, 32, 64]),
    "16x256b": (4, [1, 2, 4, 8, 16, 32]),
}


def fn_name(op, shape, n):
    return f"tmem_{op}_{shape}_x{n}"


def main():
    out = ["// Generated by scripts/gen_tmem_ops.py. Do not edit.",
           "#pragma once", "#include <cstdint>", ""]
    for shape, (per, reps) in SHAPES.items():
        for n in reps:
            k = per * n
            regs = ",".join(f"%{i}" for i in range(k))
            outs = ", ".join(f'"=r"(r[{i}])' for i in range(k))
            ins = ", ".join(f'"r"(r[{i}])' for i in range(k))
            out.append(f"__device__ __forceinline__ void {fn_name('ld', shape, n)}(uint32_t taddr, uint32_t *r) {{")
            out.append(f'  asm volatile("tcgen05.ld.sync.aligned.{shape}.x{n}.b32 {{{regs}}}, [%{k}];" : {outs} : "r"(taddr));')
            out.append("}")
            out.append(f"__device__ __forceinline__ void {fn_name('st', shape, n)}(uint32_t taddr, const uint32_t *r) {{")
            out.append(f'  asm volatile("tcgen05.st.sync.aligned.{shape}.x{n}.b32 [%{k}], {{{regs}}};" :: {ins}, "r"(taddr) : "memory");')
            out.append("}")
    out.append("")
    out.append("#define TMEM_FORMS(X) \\")
    forms = [(shape, per, n) for shape, (per, reps) in SHAPES.items() for n in reps]
    out.append(" \\\n".join(f"  X({shape}, {per}, {n})" for shape, per, n in forms))
    out.append("")
    p = os.path.join(os.path.dirname(__file__), "..", "src", "tmem_ops.cuh")
    open(p, "w").write("\n".join(out))


if __name__ == "__main__":
    main()
